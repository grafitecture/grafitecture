#!/usr/bin/env node
// Checks every row of seo/redirect-map.csv (and the trailing-slash variants) against a running site:
// status as in the map, Location = target, exactly one hop (the target answers 200 itself), target not noindex.
// Writes seo/redirect-report.md and exits 1 on any error. No dependencies (Node 18+).
//
//   node scripts/check-redirects.mjs [BASE_URL]        default http://127.0.0.1:8080 (python3 scripts/serve.py)
//   BASE_URL=https://www.grafitecture.de node scripts/check-redirects.mjs
//   Preview deployments behind Vercel Authentication: set VERCEL_AUTOMATION_BYPASS_SECRET.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = (process.argv[2] || process.env.BASE_URL || 'http://127.0.0.1:8080').replace(/\/$/, '');
const headers = { 'user-agent': 'grafitecture-redirect-check' };
if (process.env.VERCEL_AUTOMATION_BYPASS_SECRET) headers['x-vercel-protection-bypass'] = process.env.VERCEL_AUTOMATION_BYPASS_SECRET;

function parseCsv(text) {
  const [head, ...lines] = text.trim().split(/\r?\n/);
  const keys = head.split(',');
  return lines.filter(Boolean).map((line) => {
    const cells = []; let cur = ''; let q = false;
    for (const ch of line) {
      if (ch === '"') q = !q; else if (ch === ',' && !q) { cells.push(cur); cur = ''; } else cur += ch;
    }
    cells.push(cur);
    return Object.fromEntries(keys.map((k, i) => [k, cells[i] ?? '']));
  });
}

const cases = [];
const vercel = JSON.parse(readFileSync(join(ROOT, 'vercel.json'), 'utf8'));
for (const r of parseCsv(readFileSync(join(ROOT, 'seo', 'redirect-map.csv'), 'utf8'))) {
  const sample = r.alt.replace(/:(\w+)\*/g, 'beispiel').replace(/:(\w+)/g, 'beispiel');
  const variants = /\.\w+$/.test(r.alt) || r.alt.endsWith('*') ? [sample] : [sample, sample + '/'];
  for (const v of variants) cases.push({ from: v, to: r.neu, status: Number(r.status), why: r.grund });
}
// the pages themselves: with a trailing slash → without (from vercel.json, generated by build.py)
for (const r of vercel.redirects) {
  if (!r.has && r.source.endsWith('/') && r.source !== '/' && r.destination === r.source.slice(0, -1) && !cases.some((c) => c.from === r.source)) {
    cases.push({ from: r.source, to: r.destination, status: 308, why: 'kanonische Adresse ohne Schrägstrich' });
  }
}

async function get(url, method = 'GET') {
  const res = await fetch(url, { method, redirect: 'manual', headers });
  const body = method === 'GET' && res.status === 200 ? await res.text() : '';
  return { status: res.status, location: res.headers.get('location'), robots: res.headers.get('x-robots-tag') || '', body };
}

const rows = [];
let errors = 0;
for (const c of cases) {
  const problems = [];
  let r;
  try { r = await get(BASE + c.from, 'HEAD'); } catch (e) { problems.push('Fehler: ' + e.message); r = {}; }
  if (r.status !== c.status) problems.push(`Status ${r.status} statt ${c.status}`);
  const loc = r.location ? new URL(r.location, BASE + c.from) : null;
  const want = new URL(c.to, BASE + '/');
  if (!loc) problems.push('kein Location-Header');
  else if (loc.pathname + loc.search + loc.hash !== want.pathname + want.search + want.hash) problems.push(`Location ${r.location} statt ${c.to}`);
  if (loc) {
    const t = await get(new URL(loc.pathname + loc.search, BASE).href);   // the fragment never reaches the server
    if (t.status !== 200) problems.push(`Ziel antwortet ${t.status} (mehr als ein Hop oder kaputt)`);
    // previews on *.vercel.app are noindex on purpose; there only the page's own meta tag counts
    const previewHost = new URL(BASE).host.endsWith('.vercel.app');
    if ((!previewHost && /noindex/i.test(t.robots)) || /<meta name="robots" content="[^"]*noindex/i.test(t.body)) {
      if (!/\.(xml|png|ico|txt)$/.test(loc.pathname)) problems.push('Ziel ist noindex');
    }
  }
  if (problems.length) errors++;
  rows.push(`| \`${c.from}\` | \`${c.to}\` | ${r.status ?? '–'} | ${problems.length ? '❌ ' + problems.join('; ') : '✅'} |`);
}

// unknown addresses must answer 404, not 200 (no soft 404)
for (const path of ['/gibt-es-nicht-' + Date.now(), '/wp-login.php', '/wp-admin/', '/xmlrpc.php', '/.env', '/.git/config', '/feed']) {
  const r = await get(BASE + path, 'HEAD');
  const good = r.status === 404;
  if (!good) errors++;
  rows.push(`| \`${path}\` | (404) | ${r.status} | ${good ? '✅' : '❌ erwartet 404'} |`);
}

const report = `# Redirect-Report

Geprüft gegen \`${BASE}\` am ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC.
${cases.length} Weiterleitungen aus \`seo/redirect-map.csv\` und \`vercel.json\`, dazu 7 Adressen, die 404 liefern müssen.
**${errors ? errors + ' Fehler' : 'Alle in Ordnung'}.**

| Alt | Neu | Status | Ergebnis |
|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(join(ROOT, 'seo', 'redirect-report.md'), report);
console.log(report);
process.exit(errors ? 1 : 0);
